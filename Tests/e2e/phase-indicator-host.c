#include "phase-indicator-host.h"
#include <Guid/MuVarPolicyFoundationDxe.h>

struct HOST_EVENT { UINTN Tpl; EFI_EVENT_NOTIFY Notify; void *Context; EFI_GUID *Group; bool Closed; };
struct HOST_POLICY { EFI_GUID *Namespace; UINT32 Min, Max, Must, Cant; UINT8 Lock; };
static struct HOST_EVENT Events[8];
static struct HOST_POLICY Policies[2];
static size_t EventCount, PolicyCount;
static EDKII_VARIABLE_POLICY_PROTOCOL PolicyProtocol;
static bool Present[3], InjectFailure;
static unsigned CreateCount[3];
static EFI_STATUS LastSetStatus;
unsigned HostAssertions;
BOOLEAN mEfiAtRuntime;
EFI_GUID gEfiEndOfDxeEventGroupGuid = {1}, gEfiEventReadyToBootGuid = {2};
EFI_GUID gEfiEventExitBootServicesGuid = {3}, gEfiEventBeforeExitBootServicesGuid = {4};
EFI_GUID gEdkiiVariablePolicyProtocolGuid = {5};
EFI_GUID gMuVarPolicyDxePhaseGuid = {6}, gMuVarPolicyWriteOnceStateVarGuid = {7};

/* Verbatim public RuntimeLibExitBootServicesEvent, generated by the runner. */
#include "runtime-transition.inc"

static EFI_STATUS Locate(EFI_GUID *Guid, void *Registration, void **Interface) {
  (void)Registration; assert(Guid == &gEdkiiVariablePolicyProtocolGuid);
  *Interface = &PolicyProtocol; return EFI_SUCCESS;
}
static EFI_STATUS CreateEvent(UINT32 Type, UINTN Tpl, EFI_EVENT_NOTIFY Notify, void *Context,
                             EFI_GUID *Group, EFI_EVENT *Event) {
  assert(Type == EVT_NOTIFY_SIGNAL && EventCount < 8);
  *Event = &Events[EventCount++];
  **Event = (struct HOST_EVENT){Tpl, Notify, Context, Group, false};
  return EFI_SUCCESS;
}
static EFI_STATUS CloseEvent(EFI_EVENT Event) {
  assert(!Event->Closed); Event->Closed = true; return EFI_SUCCESS;
}
EFI_STATUS RegisterBasicVariablePolicy(EDKII_VARIABLE_POLICY_PROTOCOL *Protocol, EFI_GUID *Namespace,
  CHAR16 *Name, UINT32 Min, UINT32 Max, UINT32 Must, UINT32 Cant, UINT8 Lock) {
  assert(Protocol == &PolicyProtocol && Name == NULL && PolicyCount < 2);
  Policies[PolicyCount++] = (struct HOST_POLICY){Namespace, Min, Max, Must, Cant, Lock};
  return EFI_SUCCESS;
}
static int NameIndex(const CHAR16 *Name) {
  if (Name[0] == 'E' && Name[1] == 'O' && Name[2] == 'D' && Name[3] == 0) return 0;
  if (Name[0] == 'R' && Name[1] == 'T' && Name[2] == 'B' && Name[3] == 0) return 1;
  if (Name[0] == 'E' && Name[1] == 'B' && Name[2] == 'S' && Name[3] == 0) return 2;
  abort();
}
static EFI_STATUS SetVariable(CHAR16 *Name, EFI_GUID *Namespace, UINT32 Attributes, UINTN Size, void *Data) {
  int i = NameIndex(Name); assert(Namespace == &gMuVarPolicyDxePhaseGuid);
  assert(PolicyCount == 2 && Policies[0].Namespace == Namespace);
  assert(Attributes == 6 && Size == 1 && *(BOOLEAN *)Data == TRUE);
  if (Present[i]) LastSetStatus = EFI_WRITE_PROTECTED;
  else if (mEfiAtRuntime && !(Attributes & EFI_VARIABLE_NON_VOLATILE)) LastSetStatus = EFI_INVALID_PARAMETER;
  else if (InjectFailure) LastSetStatus = EFI_OUT_OF_RESOURCES;
  else { Present[i] = true; ++CreateCount[i]; LastSetStatus = EFI_SUCCESS; }
  printf("set %d runtime=%u status=0x%llx\n", i, mEfiAtRuntime, (unsigned long long)LastSetStatus);
  return LastSetStatus;
}
static EFI_BOOT_SERVICES Boot = {Locate, CreateEvent, CloseEvent};
static EFI_RUNTIME_SERVICES Runtime = {SetVariable};
EFI_BOOT_SERVICES *gBS = &Boot;
EFI_RUNTIME_SERVICES *gRT = &Runtime;

/* Include the exact chosen production translation unit, not a reimplementation. */
#include POLICY_SOURCE

static void Signal(EFI_GUID *Group) {
  /* UEFI event notifications run in descending TPL order. */
  for (int Tpl = 31; Tpl >= 0; --Tpl)
    for (size_t i = 0; i < EventCount; ++i)
      if (!Events[i].Closed && Events[i].Group == Group && Events[i].Tpl == (UINTN)Tpl)
        Events[i].Notify(&Events[i], Events[i].Context);
}
static bool AttemptExit(bool ValidMapKey) {
  /* Pinned DxeMain: the before group is signaled once, even across retries. */
  static bool Called;
  if (!Called) { Signal(&gEfiEventBeforeExitBootServicesGuid); Called = true; }
  if (!ValidMapKey) return false;
  Signal(&gEfiEventExitBootServicesGuid); return true;
}
int main(int argc, char **argv) {
  assert(argc == 2); bool Unfixed = strcmp(argv[1], "unfixed") == 0;
  bool Missing = strcmp(argv[1], "missing-phases") == 0;
  bool Retry = strcmp(argv[1], "retry") == 0;
  bool Failure = strcmp(argv[1], "service-failure") == 0;
  EFI_EVENT RuntimeEvent;
  assert(CreateEvent(EVT_NOTIFY_SIGNAL, TPL_NOTIFY, RuntimeLibExitBootServicesEvent, NULL,
    &gEfiEventExitBootServicesGuid, &RuntimeEvent) == EFI_SUCCESS);
  assert(MuVarPolicyFoundationDxeMain(NULL, NULL) == EFI_SUCCESS);
  assert(PolicyCount == 2);
  for (size_t i = 0; i < PolicyCount; ++i) {
    assert(Policies[i].Min == 1 && Policies[i].Max == 1 && Policies[i].Must == 6);
    assert(Policies[i].Cant == (UINT32)~6U && Policies[i].Lock == VARIABLE_POLICY_TYPE_LOCK_ON_CREATE);
  }
  if (!Missing) { Signal(&gEfiEndOfDxeEventGroupGuid); Signal(&gEfiEventReadyToBootGuid); }
  InjectFailure = Failure;
  if (Retry) {
    assert(!AttemptExit(false)); assert(!mEfiAtRuntime && Present[2] && HostAssertions == 0);
    assert(CreateCount[2] == 1);
  }
  assert(AttemptExit(true) && mEfiAtRuntime);
  if (Unfixed || Failure) {
    assert(HostAssertions == 1 && !Present[2]);
    assert(LastSetStatus == (Unfixed ? EFI_INVALID_PARAMETER : EFI_OUT_OF_RESOURCES));
  } else {
    assert(HostAssertions == 0);
    for (int i = 0; i < 3; ++i) assert(Present[i] && CreateCount[i] == 1);
    Signal(&gEfiEndOfDxeEventGroupGuid); Signal(&gEfiEventReadyToBootGuid);
    assert(AttemptExit(true)); assert(HostAssertions == 0);
    for (int i = 0; i < 3; ++i) assert(CreateCount[i] == 1);
    BOOLEAN Value = TRUE;
    assert(SetVariable(EXIT_BOOT_SERVICES_INDICATOR_VAR_NAME, &gMuVarPolicyDxePhaseGuid, 6, 1, &Value) == EFI_WRITE_PROTECTED);
  }
  printf("PASS %s assertions=%u EOD=%u RTB=%u EBS=%u\n", argv[1], HostAssertions,
    CreateCount[0], CreateCount[1], CreateCount[2]);
  return 0;
}
