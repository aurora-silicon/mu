def gen_cpus_asi(name, facts, socs):
    """The DSDT's processor container tree, as silicon-tier data.

    A DSDT is a board table, but its \\_SB CPU tree is not a property of the
    board -- it is the die's topology, spelled in AML. Keeping it inside each
    board's DSDT is what made every T602X machine carry J414s' ten-core tree
    regardless of its own silicon. Emitting it here lets a board DSDT say
    #include <Acpi/Cpus.asi> and get the topology of the SoC it was built for.

    ACPI0010 is the processor container HID and ACPI0007 the processor HID.

    THE BIN, AGAIN

    This is the die, so on a binned machine it names cores that are not fused
    on, and their _STA still answers 0xF. That is an overstatement but not the
    dangerous one: Windows enumerates processors from the MADT -- which
    AcpiPlatformDxe trims against the live ADT -- and correlates DSDT devices to
    it by _UID. A device with no MADT entry backs no processor and is not
    started. Making _STA answer honestly needs a value only the ADT knows, so it
    would have to be patched at install time the way the MADT is; worth doing,
    not needed for the boot to be correct.
    """
    c = facts["cpu"]
    marketing = marketing_name(socs[0])
    dies = {}
    for cl in c["clusters"]:
        dies.setdefault(0 if cl["id"] < 8 else 1, []).append(cl)

    #
    # An ACPI name segment is exactly four characters (ACPI 6.4, 20.2.2), so the
    # obvious CPU0..CPU31 and CLU0..CLU10 spellings break the moment a part has
    # more than ten of either -- and the Ultra parts number their second die's
    # clusters 8, 9 and 10. Zero-padded fixed-width names hold for every part
    # here: 32 cores on an M3 Ultra and six clusters per die.
    #
    def cpu_name(uid):
        return "C%03d" % uid

    def cluster_name(cid):
        return "CL%02d" % cid

    out = []
    for die, clusters in sorted(dies.items()):
        out.append(f"Device (DIE{die}) {{")
        out.append('    Name (_HID, "ACPI0010")')
        out.append(f"    Name (_UID, {die})")
        for idx, cl in enumerate(clusters):
            kind = "Efficiency" if cl["kind"] == "E" else "Performance"
            out.append("")
            out.append(f"    // {cl['count']} {kind.lower()} core(s), device-tree cluster {cl['id']}.")
            out.append(f"    Device ({cluster_name(cl['id'])}) {{")
            out.append('        Name (_HID, "ACPI0010")')
            out.append(f"        Name (_UID, {cl['id'] + 1})")
            for i in range(cl["count"]):
                uid = cl["uid_base"] + i
                label = f"{marketing} {kind} Core {i}"
                out.append("")
