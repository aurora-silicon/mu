def pcie_windows(facts):
    """PCIe config and BAR windows a core-system window does not already cover.

    The core windows are the 1GB blocks around everything /soc declares, and on
    some SoCs the root complex sits inside one of them. Emitting the window
    twice would spend two entries of a fixed-size descriptor table mapping the
    same pages with the same attributes.
    """
    core = [(w["base"], w["base"] + w["size"]) for w in facts["mmio"]]

    def covered(base, size):
        return any(lo <= base and base + size <= hi for lo, hi in core)

    out = []
    for p in facts["pcie"]:
        cands = [(p["ecam_base"], 0x10000000, f"{p['name']} ({p['die']}) config space")]
        for r in p["ranges"]:
            if r["space"] in ("mem32", "mem64"):
                cands.append((r["parent"], r["size"],
                              f"{p['name']} {r['space']} BAR window"))
        for base, size, what in cands:
            if base is None or covered(base, size):
                continue
            out.append({"base": base, "size": size, "what": what})
    return out


