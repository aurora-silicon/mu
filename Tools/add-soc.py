def copy_from_template(name, template, facts, socs):
    """MemoryInitPeiLib, MsPlatformDevicesLib and GTDT.

    These carry no SoC-specific data of their own -- the memory-init library
    reads its window list from the generated header, the device library only
    describes the console, and the GTDT is entirely PCD-driven. Copying keeps
    one implementation rather than a generated near-duplicate per family.
    """
    src = SILICON / f"{template}FamilyPkg"
    dst = SILICON / f"{name}FamilyPkg"
    pkg = f"{name}FamilyPkg"
    tpkg = f"{template}FamilyPkg"

    for rel in ("Library/MemoryInitPeiLib", "Library/MsPlatformDevicesLib"):
        shutil.copytree(src / rel, dst / rel)

    shutil.copy(src / "AcpiTables/GTDT.aslc", dst / "AcpiTables/GTDT.aslc")

    for path in list(dst.rglob("*.c")) + list(dst.rglob("*.inf")) + list(dst.rglob("*.aslc")):
        text = path.read_text(encoding="utf-8")
        text = (text.replace(tpkg, pkg)
                    .replace(f"{template}Family", f"{name}Family")
                    .replace(template, name.upper() if template.isupper() else name))
        if path.suffix == ".inf":
            # FILE_GUID must be unique per module or the build silently keeps
            # only one of the two.
            import re
            text = re.sub(r"(FILE_GUID\s*=\s*)[0-9a-fA-F-]{36}",
                          lambda m: m.group(1) + guid(pkg, path.parent.name),
                          text)
        path.write_text(text, encoding="utf-8")

    # The window list is the one part of the memory-init library that is data.
    mem = dst / "Library/MemoryInitPeiLib/MemoryInitPeiLib.c"
    text = mem.read_text(encoding="utf-8")
    core = "\n".join(
        f"  MAP_DEVICE_RANGE (APPLE_CORE_SYSTEM_MMIO_RANGE_{i}_BASE,  "
        f"APPLE_CORE_SYSTEM_MMIO_RANGE_{i}_SIZE);"
        for i in range(1, len(facts["mmio"]) + 1))
    n_pcie = len(pcie_windows(facts))
    pcie = "\n".join(
        f"  MAP_DEVICE_RANGE (APPLE_PCIE_MMIO_RANGE_{i}_BASE, APPLE_PCIE_MMIO_RANGE_{i}_SIZE);"
        for i in range(1, n_pcie + 1))
    if not pcie:
        pcie = ("  //\n"
                "  // No PCIe root complex is described for this family; see the\n"
                "  // memory map header.\n"
                "  //")

    import re
    text, n = re.subn(
        r"(#undef MAP_DEVICE_RANGE)",
        lambda m: m.group(1),
        text)
    # Replace everything between the macro definition and its #undef.
    begin = text.index("} while (FALSE)") + len("} while (FALSE)")
    end = text.index("#undef MAP_DEVICE_RANGE")
    text = text[:begin] + f"""

  //
  // Core system MMIO, generated from the device tree. See the memory map
  // header for how the windows were chosen.
  //
{core}

  //
  // PCIe: config space, then the BAR windows decoded from `ranges`. Without
  // these, enumerating the bus and placing a BAR would fault.
  //
{pcie}

""" + text[end:]
    #
    # The descriptor array is a fixed allocation and the template's bound was
    # written for the template's window count. It has to move with the list
    # generated above, or a family with more windows writes past the end of it.
    #
    n_core = len(facts["mmio"])
    needed = n_core + n_pcie + 3          # + DRAM + framebuffer + terminator
    text, subs = re.subn(
        r"//\n// \w+ uses \d+ core MMIO ranges.*?\n//\n"
        r"#define MAX_VIRTUAL_MEMORY_MAP_DESCRIPTORS \d+",
        "//\n"
        f"// {socs[0].upper()} uses {n_core} core MMIO range(s) + {n_pcie} PCIe range(s) + DRAM +\n"
        f"// framebuffer + terminator = {needed} descriptors, plus headroom.\n"
        "// Generated alongside the window list above -- keep the two in step.\n"
        "//\n"
        f"#define MAX_VIRTUAL_MEMORY_MAP_DESCRIPTORS {needed + 4}",
        text, count=1, flags=re.S)
    if subs != 1:
        raise SystemExit(
            "add-soc: could not retarget MAX_VIRTUAL_MEMORY_MAP_DESCRIPTORS in "
            f"{template}FamilyPkg's memory-init library. Refusing to emit one "
            "whose descriptor bound was sized for a different SoC.")
    mem.write_text(text, encoding="utf-8")


def generate(name, dtb, socs, template, machines, cpu_ssdt=True, boot_uid=0,
             caveats=""):
    facts = socfacts.facts(dtb)
    dst = SILICON / f"{name}FamilyPkg"
    if dst.exists():
        shutil.rmtree(dst)
    (dst / "AcpiTables").mkdir(parents=True)
    (dst / "Include/Library").mkdir(parents=True)

    p = topology_prefix(name, socs)
    (dst / f"{name}FamilyPkg.dec").write_text(gen_dec(name, facts, socs))
    (dst / f"{name}FamilyPkg.dsc.inc").write_text(gen_dsc_inc(name, facts, socs))
    (dst / f"Include/Library/{name}FamilyVirtualMemoryMapDefines.h").write_text(
        gen_memmap_header(name, facts, socs))
    (dst / f"AcpiTables/{p}Topology.h").write_text(
        gen_topology_header(name, facts, socs, boot_uid))
    if cpu_ssdt:
        (dst / "AcpiTables/Cpus.asl").write_text(gen_cpus_asi(name, facts, socs))
    (dst / "AcpiTables/MADT_Static.aslc").write_text(gen_madt(name, facts, socs, boot_uid))
    (dst / "AcpiTables/PPTT.aslc").write_text(gen_pptt(name, facts, socs))
    (dst / "AcpiTables/CSRT.aslc").write_text(gen_csrt(name, facts, socs))
    (dst / "AcpiTables/CPUAcpiTables.inf").write_text(
        gen_cpu_acpi_inf(name, facts, socs, cpu_ssdt))
    (dst / "Readme.md").write_text(gen_readme(name, facts, socs, machines, caveats))

    copy_from_template(name, template, facts, socs)
    return dst, facts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?", help="family package name, e.g. T811X")
    ap.add_argument("--dtb", type=Path, help="representative machine's compiled tree")
    ap.add_argument("--socs", help="comma-separated SoC ids this package covers")
    ap.add_argument("--template", default="T8142",
                    help="proven family to copy the shared libraries from")
    ap.add_argument("--machines", default="", help="comma-separated machines, for the Readme")
    ap.add_argument("--caveats", type=Path,
                    help="markdown appended to the generated Readme, for hazards "
                         "of this silicon that firmware cannot work around")
    ap.add_argument("--boot-cpu-uid", type=int, default=0,
                    help="ACPI UID of the core firmware boots on. Its GICC must "
                         "be the MADT's first entry. Default 0; T8142 and T8140 "
                         "come up on a P-core.")
    ap.add_argument("--no-cpu-ssdt", action="store_true",
                    help="do not emit the processor-container SSDT. Needed when a "
                         "board this family serves declares processors in its own "
                         "DSDT, because two declarations of \\_SB.DIE0 collide.")
    ap.add_argument("--list", action="store_true", help="list existing family packages")
    args = ap.parse_args()

    if args.list:
        for d in sorted(SILICON.glob("*FamilyPkg")):
            n = len(list(d.rglob("*")))
            print(f"{d.name:22} {n:3} files")
        return 0

    if not (args.name and args.dtb and args.socs):
        ap.error("name, --dtb and --socs are required")

    socs = args.socs.split(",")
    machines = [m for m in args.machines.split(",") if m]
    dst, facts = generate(args.name, args.dtb, socs, args.template, machines,
                          cpu_ssdt=not args.no_cpu_ssdt, boot_uid=args.boot_cpu_uid,
                          caveats=args.caveats.read_text() if args.caveats else "")
    c = facts["cpu"]
    print(f"{args.name}FamilyPkg -> {dst.relative_to(REPO)}")
    print(f"  {facts['model']}")
    print(f"  {c['cpu_count']} cores / {len(c['clusters'])} clusters, "
          f"{len(facts['mmio'])} MMIO windows, {len(facts['pcie'])} PCIe RC")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
