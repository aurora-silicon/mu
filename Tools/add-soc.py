#!/usr/bin/env python3
"""Create a Mu SoC family package from an Asahi device tree.

WHY THIS EXISTS, AND WHAT IT DELIBERATELY DOES NOT DO
-----------------------------------------------------
A family package is the part of the firmware that describes silicon rather than
a machine: where DRAM starts, where the MMIO windows are, how many cores there
are and how they cluster, where UART0 and the PCIe root complex live. Every one
of those is a fact Asahi's device tree already states, per SoC, maintained by
people who boot Linux on the hardware.

Hand-transcribing them does not go well. T602X's hand-written memory map left a
3GB hole containing ANS; it survived review and was only found when ANS was
enabled for the first time and the first SART register read took a translation
fault on real hardware. It still has a second hole over dcpext that nothing has
touched yet. Both are covered automatically by windows derived from the tree
that declares those nodes.

So this generates. What it generates is then *committed as static source and
owned by hand*, exactly like the platform packages Tools/add-machine.py makes:
the ACPI tables have to map hardware onto the device nodes Windows drivers bind
to, and that mapping -- _HID strings, _DSD names, GSIV renumbering, AML -- is
the work and exists in no device tree. This gets a family to the point where
that work can begin, and no further.

WHAT IT CANNOT KNOW
-------------------
Three things are not in any device tree and are emitted as explicit unknowns
rather than guesses:

  * AIC geometry -- IRQ counts, register strides, capability offsets. Linux and
    m1n1 both read these off the controller at runtime. CSRT.aslc is therefore
    generated as the same documented stub T810XFamilyPkg has shipped since the
    beginning, and the machine boots without it; it is Windows' HAL extension
    that needs it filled in.
  * Which core firmware boots on. Assumed to be UID 0, which is right for every
    SoC we have measured except T8142.
  * The bin. Apple ships several core counts per die and the tree describes the
    die. See the CPU-count note in the generated Readme.

    Tools/add-soc.py --list
    Tools/add-soc.py T811X --dtb Build/DeviceTree/t8112-j413.dtb --socs t8112
"""

