def macro(lines, width=84):
    """Join lines into a C macro body, padding each to `width` before its \\.

    Generated macros span many lines and a single missing continuation turns the
    rest of the body into stray top-level tokens, so this is the only place that
    decides where a backslash goes.
    """
    out = []
    for i, line in enumerate(lines):
        if i == len(lines) - 1:
            out.append(line)
        else:
            out.append(line.ljust(width) + "\\")
    return "\n".join(out)


def gen_pptt(name, facts, socs):
    p = topology_prefix(name, socs)
    c = facts["cpu"]
    clusters = c["clusters"]

    # Ultra parts put die 1's clusters at Aff1 >= 8. Group by that so the PPTT
    # describes two dies rather than one die with six clusters.
    dies = {}
    for i, cl in enumerate(clusters):
        dies.setdefault(0 if cl["id"] < 8 else 1, []).append((i, cl))
    die_count = len(dies)
    per_die = dies[0]

    types = []
    for i, cl in per_die:
        types.append(f"""typedef struct {{
  EFI_ACPI_6_4_PPTT_STRUCTURE_PROCESSOR  Cluster;
  PPTT_CORE                              Cores[{cl['count']}];
}} PPTT_CLUSTER_{i};""")

    die_members = "\n".join(f"  PPTT_CLUSTER_{i}  Cluster{i};" for i, _ in per_die)

    cluster_macros = []
    for i, cl in per_die:
        body = [
            f"#define CLUSTER_{i}_INIT(DieId)",
            "{",
            "  EFI_ACPI_6_4_PPTT_STRUCTURE_PROCESSOR_INIT (",
            f"    OFFSET_OF (PPTT_CLUSTER_{i}, Cores),                    /* Length */",
            "    PPTT_PROCESSOR_CLUSTER_FLAGS,                          /* Flag */",
            "    OFFSET_OF (EFI_ACPI_6_4_PROCESSOR_PROPERTIES_TOPOLOGY_TABLE,",
            "      Dies[DieId].Die),                                    /* Parent */",
            f"    (((DieId) << 4) | {i}),                                  /* ACPI Id */",
            "    0                                                      /* Private resources */",
            "  ),",
            "  {",
        ]
        body += [f"    CORE_INIT (DieId, {i}, {j})," for j in range(cl["count"] - 1)]
        body += [f"    CORE_INIT (DieId, {i}, {cl['count'] - 1})"]
        body += ["  }", "}"]
        cluster_macros.append(macro(body))

    uid_expr = []
    for i, cl in per_die:
        uid_expr.append(f"#define CLUSTER_{i}_UID_BASE {cl['uid_base']}")

