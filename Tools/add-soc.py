# Deterministic GUIDs. A family package needs a package GUID, a token-space
# GUID and one FILE_GUID per module; generating them from the package name
# means re-running this tool is idempotent and two people generating the same
# package get the same file rather than a spurious diff.
GUID_NS = uuid.UUID("6f1c4f6a-6b0e-5a2e-9a37-2f4d9a2a1c00")


def guid(*parts: str) -> str:
    return str(uuid.uuid5(GUID_NS, "/".join(parts))).lower()


def guid_braced(*parts: str) -> str:
    u = uuid.uuid5(GUID_NS, "/".join(parts))
    b = u.bytes_le
    return ("{ 0x%08x, 0x%04x, 0x%04x, { %s } }"
            % (int.from_bytes(b[0:4], "little"),
               int.from_bytes(b[4:6], "little"),
               int.from_bytes(b[6:8], "little"),
               ", ".join("0x%02x" % x for x in b[8:16])))


def size_macro(n: int) -> str:
    """EDK2 spells sizes as SIZE_nGB / SIZE_nMB; fall back to hex."""
    for unit, div in (("GB", 1 << 30), ("MB", 1 << 20), ("KB", 1 << 10)):
        if n >= div and n % div == 0:
            v = n // div
            if v & (v - 1) == 0:
                return f"SIZE_{v}{unit}"
    return f"0x{n:X}"


def banner(soc_list, model):
    return f"""  Generated by Tools/add-soc.py from the device tree for
  {model}.

  Covers: {', '.join(soc_list)}

  UNVERIFIED. Every address, core count and window below is what the device
  tree states; none of it has been read off this silicon by us, and no machine
  in this family has been booted. Treat a successful build as evidence that the
  package is self-consistent and nothing more."""


